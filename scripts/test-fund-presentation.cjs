const fs = require("node:fs")
const Module = require("node:module")
const path = require("node:path")
const ts = require("typescript")
const root = path.resolve(__dirname, "..")
const resolve = Module._resolveFilename
Module._resolveFilename = (request, parent, isMain, options) => resolve(request.startsWith("@/") ? path.join(root, request.slice(2)) : request, parent, isMain, options)
require.extensions[".ts"] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true } }).outputText, filename)
const presentation = require("../components/funds/fund-presentation.ts")
const assert = (condition, message) => { if (!condition) throw new Error(message) }
const fund = (id, goal, balance, target_month = null) => ({ id, goal_amount: goal, current_balance: balance, target_month, status: "active" })
assert(presentation.getFundPresentationState(fund("open", null, "0")) === "open_ended", "open-ended funds have a distinct state")
assert(presentation.getFundPresentationState(fund("new", "100.00", "0")) === "not_started", "empty goal funds are not started")
assert(presentation.getFundPresentationState(fund("progress", "100.00", "25.00")) === "in_progress", "partially funded goals are in progress")
assert(presentation.getFundPresentationState(fund("done", "100.00", "100.00")) === "goal_reached", "fully funded goals are reached")
const groups = presentation.groupActiveFunds([fund("later", "100", "10", "2027-03"), fund("soon", "100", "10", "2026-09"), fund("open", null, "0")])
assert(groups[0].funds[0].id === "soon" && groups[1].funds[0].id === "open", "active funds are grouped and target-sorted")
assert(presentation.entryTypeLabel({ source_type: "manual", entry_type: "contribution", direction: "in" }) === "Added money", "manual entry labels remain stable")
console.log("Fund presentation tests passed")
