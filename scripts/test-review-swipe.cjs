const fs = require("node:fs")
const ts = require("typescript")
const assert = require("node:assert/strict")
require.extensions[".ts"] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, filename)
const { reviewSwipeCategory, reviewSwipeStartAllowed } = require("../lib/review-swipe.ts")
assert.equal(reviewSwipeCategory(100, 5), "needs")
assert.equal(reviewSwipeCategory(-100, 5), "wants")
assert.equal(reviewSwipeCategory(5, 100), "savings")
for (const [x, y] of [[89, 0], [0, 89], [0, -120], [100, 100], [-100, 100]]) assert.equal(reviewSwipeCategory(x, y), null)
assert.equal(reviewSwipeStartAllowed(27, 390), false)
assert.equal(reviewSwipeStartAllowed(363, 390), false)
assert.equal(reviewSwipeStartAllowed(28, 390), true)
console.log("Review gesture tests passed")
