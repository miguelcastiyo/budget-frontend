import { expect, test } from "@playwright/test"
import { setupEncryptedFixture } from "./encrypted-fixture"

test.skip(process.env.NEXT_PUBLIC_BUDGET_V2_ENABLED !== "true", "Requires interface switching")

test("Classic Home and editor stay clear and usable at narrow mobile sizes", async ({ page }) => {
  test.setTimeout(90000)
  await setupEncryptedFixture(page, true)
  await page.getByRole("navigation", { name: "Primary desktop" }).getByRole("link", { name: "More" }).click()
  await page.getByRole("switch", { name: "Use v2 interface" }).click()
  await page.setViewportSize({ width: 375, height: 520 })
  await page.getByRole("navigation", { name: "Primary", exact: true }).getByRole("link", { name: "Overview" }).click()

  await expect(page.getByText("Drill Down")).toHaveCount(0)
  await expect(page.getByText("Where the money went")).toHaveCount(0)
  await expect(page.getByRole("heading", { name: /budget$/ })).toBeVisible()
  await expect(page.getByText("$0.00", { exact: true })).toHaveCount(0)
  await expect(page.getByRole("button", { name: "Add Transaction" })).toBeVisible()
  await expect(page.getByRole("navigation", { name: "Primary", exact: true }).getByRole("link", { name: "Activity" })).toBeVisible()
  for (const width of [300, 375, 430]) {
    await page.setViewportSize({ width, height: 520 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  }

  await page.setViewportSize({ width: 300, height: 520 })
  await page.getByRole("button", { name: "Add Transaction" }).click()
  const dialog = page.getByRole("dialog")
  await expect(dialog.getByRole("heading", { name: "New Transaction" })).toBeVisible()
  await expect(dialog.getByRole("button", { name: "Quick Add" })).toBeVisible()
  await expect(dialog.locator('input[name="transaction_amount"]')).toHaveAttribute("inputmode", "numeric")
  expect(await dialog.evaluate(element => element.getBoundingClientRect().right <= window.innerWidth + 1)).toBe(true)
  await dialog.getByRole("button", { name: "Quick Add" }).click()
  await expect(dialog.getByRole("form", { name: "Quick Add" })).toBeVisible()
  expect(await dialog.getByRole("button", { name: "Save to Review" }).evaluate(element => element.getBoundingClientRect().bottom <= window.innerHeight + 1)).toBe(true)
  await page.keyboard.press("Escape")
  await expect(dialog).toHaveCount(0)
  await page.getByRole("button", { name: "Add Transaction" }).click()
  await expect(dialog.getByRole("heading", { name: "New Transaction" })).toBeVisible()
  await page.keyboard.press("Escape")
  await expect(dialog).toHaveCount(0)
  await page.getByRole("button", { name: "Set budget" }).click()
  await expect(page).toHaveURL(/\/settings\/budget\?month=/)
  await expect(page.getByRole("dialog", { name: "Edit Budget" })).toBeVisible()
})

test("Classic Review and Settings use one clear heading hierarchy", async ({ page }) => {
  test.setTimeout(90000)
  await setupEncryptedFixture(page, true)
  await page.getByRole("navigation", { name: "Primary desktop" }).getByRole("link", { name: "More" }).click()
  await page.getByRole("switch", { name: "Use v2 interface" }).click()
  await page.getByRole("link", { name: "Review", exact: true }).filter({ visible: true }).first().click()
  await expect(page.getByRole("heading", { name: "Review", exact: true, level: 1 })).toBeVisible()
  await expect(page.getByRole("heading", { name: "Quick Capture", level: 2 })).toBeVisible()
  await expect(page.getByRole("heading", { name: "Pending", level: 2 })).toBeVisible()
  await expect(page.getByText("Capture now, organize later")).toHaveCount(0)
  const capture = page.getByRole("form", { name: "Quick Capture" })
  await expect(capture.getByRole("button", { name: "Save to Review" })).toBeVisible()
  await expect(page.getByText("Enter an amount, a description, or both.")).toHaveCount(0)
  await capture.getByLabel("Amount").fill("5")
  await capture.getByRole("button", { name: "Save to Review" }).click()
  await expect(page.getByRole("status")).toContainText("Saved to Review")
  await page.getByRole("link", { name: "Settings", exact: true }).filter({ visible: true }).first().click()
  await expect(page.getByRole("link", { name: /Budget/ })).toBeVisible()
  await expect(page.getByText("Monthly plan and limits")).toHaveCount(0)
  await expect(page.getByText("Trips, events, and projects")).toBeVisible()
})

test("saved Classic budgets retain their totals and keyboard category navigation", async ({ page }) => {
  test.setTimeout(90000)
  await setupEncryptedFixture(page, true)
  await page.getByRole("navigation", { name: "Primary desktop" }).getByRole("link", { name: "More" }).click()
  await page.getByRole("switch", { name: "Use v2 interface" }).click()
  await page.getByRole("link", { name: "Overview", exact: true }).filter({ visible: true }).first().click()
  await page.getByRole("button", { name: "Set budget" }).click()
  const dialog = page.getByRole("dialog", { name: "Edit Budget" })
  await dialog.getByLabel("Monthly take-home income").fill("1000")
  await dialog.getByRole("button", { name: /Save Budget Starting/ }).click()
  await expect(dialog).toHaveCount(0)
  await page.getByRole("button", { name: "Back to settings" }).click()
  await page.getByRole("link", { name: "Overview", exact: true }).filter({ visible: true }).first().click()
  await expect(page.getByText("$1,000.00").first()).toBeVisible()
  const needs = page.getByRole("button", { name: "View Needs transactions" })
  await expect(needs).toContainText("$500.00")
  await needs.focus()
  await page.keyboard.press("Enter")
  await expect(page).toHaveURL(/\/transactions\?.*category=needs/)
})
