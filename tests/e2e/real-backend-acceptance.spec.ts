  await funds.getByRole("button", { name: "New fund" }).filter({ visible: true }).first().click()
  const fundCreate = page.getByRole("dialog", { name: "Create fund" })
  await fundCreate.getByLabel("Name", { exact: true }).fill("Acceptance fund")
  await fundCreate.getByRole("button", { name: "Create fund" }).click()
