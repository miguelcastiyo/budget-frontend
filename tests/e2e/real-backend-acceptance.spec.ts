  const recovery = await page.getByLabel("Recovery Code", { exact: true }).innerText()
  await page.getByText("I've saved my Recovery Code somewhere safe.").click()
  await page.getByLabel("Enter the last 4 characters of your Recovery Code.").fill(recovery.replace(/-/g, "").slice(-4))
  await page.getByRole("button", { name: "Continue", exact: true }).click()
  await page.goto("/")
  await page.getByRole("button", { name: "Use Vault passphrase" }).click()
  await page.getByLabel("Vault passphrase", { exact: true }).fill("isolated acceptance vault password")
  await page.getByRole("button", { name: "Unlock Vault" }).click()
  await page.getByTestId("v2-overview").getByRole("button", { name: "Set budget" }).click()
  const budget = page.getByRole("dialog", { name: "Edit Budget" })
  await budget.getByLabel("Monthly take-home income").fill("1000")
  await budget.getByRole("button", { name: /Save Budget Starting/ }).click()
  await expect(budget).toHaveCount(0)
  await page.getByTestId("v2-budget").getByRole("button", { name: "Edit budget" }).click()
  await budget.getByLabel("Monthly take-home income").fill("1200")
  await budget.getByRole("button", { name: /Update .* Budget/ }).click()
  await expect(budget).toHaveCount(0)
  await page.getByRole("link", { name: "Overview", exact: true }).first().click()
  await page.getByRole("button", { name: "Add", exact: true }).click()
  const capture = page.getByRole("form", { name: "Quick Capture" })
  await capture.getByLabel("Amount").fill("12.50")
  await capture.getByLabel("Description").fill("Acceptance expense")
  await capture.getByRole("button", { name: "Save to Review" }).click()
  await page.getByRole("link", { name: /Review/ }).first().click()
  const review = page.getByRole("form", { name: "Review transaction" })
  await review.getByRole("button", { name: /Needs/ }).click()
  await review.getByRole("button", { name: "All tags" }).click()
  const picker = page.getByRole("dialog", { name: "All tags" })
  await picker.getByLabel("New tag name").fill("Acceptance tag")
  await picker.getByRole("button", { name: "Create tag" }).click()
  await picker.getByRole("button", { name: "Done" }).click()
  await review.getByRole("button", { name: "Confirm & Next" }).click()
  await expect(page.getByRole("status").filter({ hasText: "Transaction finalized" })).toBeVisible()
  await page.getByRole("button", { name: "Undo" }).click()
  await expect(page.getByRole("status").filter({ hasText: "Returned to Review" })).toBeVisible()
  await review.getByRole("button", { name: /Needs/ }).click()
  await review.getByRole("button", { name: "Confirm & Next" }).click()
  await expect(page.getByRole("status").filter({ hasText: "Transaction finalized" })).toBeVisible()
  await page.getByRole("link", { name: "Transactions", exact: true }).first().click()
