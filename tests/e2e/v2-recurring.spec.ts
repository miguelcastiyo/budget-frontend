import { expect, test } from "@playwright/test"
import { setupEncryptedFixture } from "./encrypted-fixture"

test.skip(process.env.NEXT_PUBLIC_BUDGET_V2_ENABLED !== "true", "Requires v2 availability")
test.use({ actionTimeout: 12000 })

test("recurring transaction edit scopes distinguish one occurrence from future rules", async ({ page }) => {
  test.setTimeout(120000)
  await setupEncryptedFixture(page, true)
  await page.getByRole("button", { name: "Add", exact: true }).click()
  const quick = page.getByRole("form", { name: "Quick Capture" })
  await quick.getByLabel("Amount").fill("10.00")
  await quick.getByLabel("Description").fill("Recurring scope")
  await quick.getByRole("button", { name: "Full Entry" }).click()
  let editor = page.getByRole("dialog")
  await editor.getByRole("button", { name: "New tag" }).click()
  await editor.getByPlaceholder("Tag name").fill("Scope tag")
  await editor.getByRole("button", { name: "Add tag", exact: true }).click()
  await expect(editor.getByRole("radio", { name: "Scope tag" })).toBeVisible()
  await editor.getByRole("button", { name: /More details/ }).click()
  await editor.getByText("Automatically add this every month").locator("../..").getByRole("switch").click()
  await editor.getByLabel("Day of month").fill("17")
  await editor.getByRole("button", { name: "Add Transaction", exact: true }).click()
  await expect(editor).toHaveCount(0)
  await page.getByRole("link", { name: "Transactions", exact: true }).first().click()
  const ledger = page.getByRole("region", { name: "Activity transactions" })
  await ledger.getByRole("button", { name: /Recurring scope/ }).filter({ hasNotText: "Projected" }).click()
  await page.getByRole("dialog").getByRole("button", { name: "Edit" }).click()
  editor = page.getByRole("dialog")
  await expect(editor.getByRole("button", { name: "This transaction only" })).toHaveAttribute("aria-pressed", "true")
  await editor.getByLabel("Description", { exact: true }).fill("Single occurrence")
  await editor.getByRole("button", { name: /Save changes/i }).click()
  await expect(ledger.getByRole("button", { name: /Single occurrence/ })).toBeVisible()
  await ledger.getByRole("button", { name: /Single occurrence/ }).click()
  await page.getByRole("dialog").getByRole("button", { name: "Edit" }).click()
  editor = page.getByRole("dialog")
  await editor.getByRole("button", { name: "This and future recurring transactions" }).click()
  await editor.getByLabel("Amount", { exact: true }).fill("12.00")
  await editor.getByRole("button", { name: /Save and apply to future/i }).click()
  await expect(ledger.getByRole("button", { name: /Single occurrence/ })).toContainText("12.00")
  await page.getByRole("link", { name: "Settings", exact: true }).first().click()
  await page.locator('a[href="/settings/recurring"]').click()
  const recurring = page.getByTestId("v2-recurring")
  await recurring.getByRole("button", { name: /Open details for/ }).first().click()
  await expect(page.getByRole("dialog").getByText("Scheduled change", { exact: true })).toBeVisible()
})

test("recurring rules retain custom schedules across edits and interface versions", async ({ page }) => {
  test.setTimeout(120000)
  await setupEncryptedFixture(page, true)
  await page.getByRole("link", { name: "Settings", exact: true }).first().click()
  await page.locator('a[href="/settings/recurring"]').click()
  const recurring = page.getByTestId("v2-recurring")
  await expect(recurring).toContainText("No monthly commitments yet")
  await recurring.getByRole("button", { name: "Add commitment" }).filter({ visible: true }).first().click()
  const create = page.getByRole("dialog", { name: "New Commitment" })
  await create.locator("#recurring-amount").fill("25")
  await create.getByLabel("Description").fill("Monthly service")
  await create.getByRole("button", { name: "New tag" }).click()
  await create.getByPlaceholder("Tag name").fill("Utilities")
  await page.route("**/api/v1/me/encrypted-records", async (route) => { await new Promise((resolve) => setTimeout(resolve, 500)); await route.fallback() })
  await create.getByRole("button", { name: "Add tag", exact: true }).click()
  await create.locator('input[type="number"]').fill("17")
  await create.getByRole("switch", { name: "Recurring expense active" }).click()
  await expect(create.getByRole("radio", { name: "Utilities" })).toBeVisible()
  await expect(create.locator('input[type="number"]')).toHaveValue("17")
  await expect(create.getByRole("switch", { name: "Recurring expense active" })).not.toBeChecked()
  await page.unroute("**/api/v1/me/encrypted-records")
  await page.route("**/api/v1/me/encrypted-records", (route) => route.fulfill({ status: 500, json: { error: { code: "TEST_FAILURE", message: "Save failed" } } }))
  await create.getByRole("button", { name: "Create commitment" }).click()
  const globalError = page.getByRole("dialog", { name: "Something went wrong" })
  await expect(globalError).toBeVisible()
  await globalError.getByRole("button", { name: "Close" }).first().click()
  await expect(create.getByRole("alert")).toBeVisible()
  await expect(create.locator('input[type="number"]')).toHaveValue("17")
  await expect(create.getByLabel("Description")).toHaveValue("Monthly service")
  await page.unroute("**/api/v1/me/encrypted-records")
  await create.getByRole("button", { name: "Create commitment" }).click()
  await expect(create).toHaveCount(0)
  await recurring.getByRole("button", { name: "Open details for Monthly service" }).click()
  let detail = page.getByRole("dialog", { name: "Monthly service" })
  await expect(detail).toContainText("Day 17 monthly")
  await expect(detail).toContainText("monthly rule")
  await detail.getByRole("button", { name: "Edit current version" }).click()
  const edit = page.getByRole("dialog", { name: "Edit Commitment" })
  await expect(edit.locator('input[type="number"]')).toHaveValue("17")
  await edit.getByLabel("Description").fill("Monthly service updated")
  await edit.getByRole("button", { name: "Save changes" }).click()
  await expect(edit).toHaveCount(0)
  await recurring.getByRole("button", { name: "Open details for Monthly service updated" }).click()
  detail = page.getByRole("dialog", { name: "Monthly service updated" })
  await expect(detail).toContainText("Day 17 monthly")
  await detail.getByRole("button", { name: "Close" }).click()
  await page.getByRole("button", { name: "Back to settings" }).click()
  await page.getByRole("switch", { name: "Use v2 interface" }).click()
  await page.locator('a[href="/settings/recurring"]').click()
  await expect(page.getByTestId("v2-recurring")).toHaveCount(0)
  await page.getByRole("button", { name: "Open details for Monthly service updated" }).click()
  await expect(page.getByRole("dialog", { name: "Monthly service updated" })).toContainText("Day 17 monthly")
  await page.getByRole("dialog", { name: "Monthly service updated" }).getByRole("button", { name: "Edit current version" }).click()
  const classicEdit = page.getByRole("dialog", { name: "Edit Commitment" })
  await classicEdit.getByRole("combobox").click()
  await page.getByRole("option", { name: "Last day" }).click()
  await classicEdit.getByRole("button", { name: "Save changes" }).click()
  await expect(classicEdit).toHaveCount(0)
  await page.getByRole("button", { name: "Open details for Monthly service updated" }).click()
  await expect(page.getByRole("dialog", { name: "Monthly service updated" })).toContainText("Last day monthly")
})

test("v2 recurring dialogs and nested schedule selectors fit mobile and desktop", async ({ page }) => {
  test.setTimeout(90000)
  await setupEncryptedFixture(page, true)
  await page.getByRole("link", { name: "Settings", exact: true }).first().click()
  await page.locator('a[href="/settings/recurring"]').click()
  const recurring = page.getByTestId("v2-recurring")
  for (const width of [375, 430, 1280]) {
    await page.setViewportSize({ width, height: 844 })
    for (const dark of [false, true]) {
      await page.evaluate((value) => document.documentElement.classList.toggle("dark", value), dark)
      await recurring.getByRole("button", { name: "Add commitment" }).filter({ visible: true }).first().click()
      const dialog = page.getByRole("dialog", { name: "New Commitment" })
      await expect(dialog).toHaveCSS("background-color", dark ? "rgb(22, 23, 26)" : "rgb(251, 251, 250)")
      await dialog.getByRole("combobox").click()
      const picker = page.getByRole("listbox")
      await expect(picker).toHaveCSS("background-color", dark ? "rgb(22, 23, 26)" : "rgb(251, 251, 250)")
      await page.keyboard.press("Escape")
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await dialog.getByRole("button", { name: "Close" }).click()
    }
  }
})
