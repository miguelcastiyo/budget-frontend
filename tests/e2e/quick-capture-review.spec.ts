import { expect, test } from "@playwright/test"
import { execFileSync } from "node:child_process"
import { randomBytes } from "node:crypto"
import path from "node:path"

// Run only against the dedicated encrypted parity database and local backend.
test("Quick Capture and Review persist, skip, finalize, and undo", async ({ page }) => {
  test.setTimeout(90000)
  test.skip(process.env.PENDING_UI_E2E !== "1", "Requires the isolated pending development backend")
  const backend = path.resolve(process.cwd(), "../budget-backend")
  const raw = execFileSync("php", ["scripts/seed_encrypted_default_browser_account.php"], { cwd: backend, env: { ...process.env, PRIVACY_PARITY_TEST: "1", ENCRYPTED_DEFAULT_BROWSER_SUFFIX: randomBytes(8).toString("hex") }, encoding: "utf8" })
  const account = JSON.parse(raw) as { session_token: string; csrf_token: string }
  await page.context().addCookies([{ name: "sid", value: account.session_token, domain: "127.0.0.1", path: "/" }])
  await page.goto("/sign-in")
  await page.evaluate((csrf) => window.localStorage.setItem("budget.csrf_token", csrf), account.csrf_token)
  await page.goto("/settings/vault")
  await page.getByTestId("privacy-setup-start").click()
  await page.getByLabel("Vault passphrase", { exact: true }).fill("pending local test passphrase")
  await page.getByLabel("Confirm Vault passphrase", { exact: true }).fill("pending local test passphrase")
  await page.getByRole("button", { name: "Continue", exact: true }).click()
  const code = await page.getByLabel("Recovery Code", { exact: true }).innerText()
  await page.getByText("I've saved my Recovery Code somewhere safe.").click()
  await page.getByLabel("Enter the last 4 characters of your Recovery Code.").fill(code.replace(/-/g, "").slice(-4))
  await page.getByRole("button", { name: "Continue", exact: true }).click()
  await page.goto("/review")
  await page.getByRole("button", { name: "Use Vault passphrase" }).click()
  await page.getByLabel("Vault passphrase", { exact: true }).fill("pending local test passphrase")
  await page.getByRole("button", { name: "Unlock Vault" }).click()
  const capture = page.getByRole("form", { name: "Quick Capture" })
  await capture.getByRole("button", { name: "Save expense" }).click()
  await expect(page.getByText("Enter a positive amount, a description, or both, and use a valid date.")).toBeVisible()
  await capture.getByLabel("Amount").fill("12.50")
  await capture.getByRole("button", { name: "Save expense" }).click()
  await expect(page.getByRole("status")).toContainText("Saved to Review")
  await capture.getByLabel("Description").fill("Coffee")
  await capture.getByRole("button", { name: "Save expense" }).click()
  await expect(page.getByText("2 pending", { exact: true })).toBeVisible()
  let review = page.getByRole("form", { name: "Review transaction" })
  await expect(review.getByLabel("Amount")).toHaveValue("12.50")
  await review.getByRole("button", { name: "Skip" }).click()
  await expect(review.getByLabel("Description")).toHaveValue("Coffee")
  await expect(page.getByText("2 pending", { exact: true })).toBeVisible()
  await expect(page.getByLabel("Review progress")).toHaveText("0 finalized · 1 skipped")
  await review.getByLabel("Amount").fill("3.25")
  const swipe = review.getByTestId("review-swipe-card")
  const swipeBy = async (x: number, y: number) => {
    const box = await swipe.boundingBox()
    if (!box) throw new Error("Review card not visible")
    const startX = box.x + box.width / 2, startY = box.y + box.height / 2
    await page.mouse.move(startX, startY); await page.mouse.down(); await page.mouse.move(startX + x, startY + y, { steps: 5 }); await page.mouse.up()
    await page.waitForTimeout(220)
  }
  await swipeBy(35, 0)
  await expect(review.getByRole("button", { name: "Needs" })).toHaveAttribute("aria-pressed", "false")
  await swipeBy(110, 0)
  await expect(review.getByRole("button", { name: "Needs" })).toHaveAttribute("aria-pressed", "true")
  await swipeBy(0, 110)
  await expect(review.getByRole("button", { name: "Savings" })).toHaveAttribute("aria-pressed", "true")
  await swipeBy(-110, 0)
  await expect(review.getByRole("button", { name: "Wants" })).toHaveAttribute("aria-pressed", "true")
  await review.getByRole("button", { name: "Needs" }).focus()
  await page.keyboard.press("Space")
  await expect(review.getByRole("button", { name: "Needs" })).toHaveAttribute("aria-pressed", "true")
  await review.getByRole("button", { name: "Wants" }).focus()
  await page.keyboard.press("Space")
  await expect(review.getByRole("button", { name: "Wants" })).toHaveAttribute("aria-pressed", "true")
  await page.emulateMedia({ reducedMotion: "reduce" })
  await expect(swipe).toHaveCSS("transition-duration", "0s")
  await review.getByRole("button", { name: "Finalize" }).click()
  await expect(page.getByText("Choose and confirm an active tag.")).toBeVisible()
  await review.getByLabel("New tag name").fill("Cafe")
  await review.getByRole("button", { name: "Add", exact: true }).click()
  await page.route("**/api/v1/me/encrypted-records/batch", (route) => route.fulfill({ status: 409, json: { error: { code: "ENCRYPTED_RECORD_REVISION_CONFLICT", message: "Conflict" } } }))
  await review.getByRole("button", { name: "Finalize" }).click()
  await expect(page.getByText("This item changed on another device. Sync and review it again.")).toBeVisible()
  await expect(page.getByText("2 pending", { exact: true })).toBeVisible()
  await page.unroute("**/api/v1/me/encrypted-records/batch")
  await review.getByRole("button", { name: "Finalize" }).click()
  await expect(page.getByRole("status")).toContainText("Transaction finalized")
  await expect(page.getByText("1 pending", { exact: true })).toBeVisible()
  await expect(page.getByLabel("Review progress")).toHaveText("1 finalized · 1 skipped")
  await page.getByRole("button", { name: "Undo" }).click()
  await expect(page.getByRole("status")).toContainText("Returned to Review")
  await expect(page.getByText("2 pending", { exact: true })).toBeVisible()
  await expect(page.getByLabel("Review progress")).toHaveText("0 finalized · 1 skipped")
  review = page.getByRole("form", { name: "Review transaction" })
  await expect(review.getByLabel("Description")).toHaveValue("Coffee")
  await review.getByRole("button", { name: "Skip" }).click()
  await expect(page.getByText("You’ve reached the end of this pass.")).toBeVisible()
  await expect(page.getByLabel("Review progress")).toHaveText("0 finalized · 2 skipped")
  await page.getByRole("button", { name: "Review skipped items" }).click()
  await expect(page.getByLabel("Review progress")).toHaveText("0 finalized · 0 skipped")
  await expect(page.locator("header").getByLabel("2 pending")).toBeVisible()
  await page.locator("header").getByRole("link", { name: "Overview" }).click()
  await expect(page.getByRole("link", { name: /2 pending.*known.*Review/ })).toBeVisible()
  await page.locator("header").getByRole("link", { name: /Review/ }).click()
  await page.reload()
  await expect(page.getByTestId("encrypted-vault-locked-boundary")).toBeVisible()
  await page.getByRole("button", { name: "Use Vault passphrase" }).click()
  await page.getByLabel("Vault passphrase", { exact: true }).fill("pending local test passphrase")
  await page.getByRole("button", { name: "Unlock Vault" }).click()
  await expect(page.locator("header").getByLabel("2 pending")).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole("navigation", { name: "Primary" }).getByLabel("2 pending")).toBeVisible()
  await page.getByRole("navigation", { name: "Primary" }).getByRole("link", { name: /Review/ }).click()
  const mobileCard = page.getByTestId("review-swipe-card")
  await mobileCard.scrollIntoViewIfNeeded()
  if (page.context().browser()?.browserType().name() === "chromium") {
    const client = await page.context().newCDPSession(page)
    const box = await mobileCard.boundingBox()
    if (!box) throw new Error("Mobile review card not visible")
    const x = box.x + box.width / 2, y = box.y + box.height / 2
    await client.send("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: [{ x, y }] })
    await client.send("Input.dispatchTouchEvent", { type: "touchMove", touchPoints: [{ x: x + 110, y }] })
    await client.send("Input.dispatchTouchEvent", { type: "touchEnd", touchPoints: [] })
    await expect(page.getByRole("button", { name: "Needs" })).toHaveAttribute("aria-pressed", "true")
    await client.send("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: [{ x, y }] })
    await client.send("Input.dispatchTouchEvent", { type: "touchMove", touchPoints: [{ x: x - 110, y }] })
    await client.send("Input.dispatchTouchEvent", { type: "touchCancel", touchPoints: [] })
    await expect(page.getByRole("button", { name: "Needs" })).toHaveAttribute("aria-pressed", "true")
    await client.detach()
  }
  await page.setViewportSize({ width: 1280, height: 800 })
  await page.locator("header").getByRole("link", { name: /Review/ }).click()
  await page.getByRole("link", { name: "Full transaction entry" }).click()
  await expect(page.getByRole("heading", { name: "New Transaction" })).toBeVisible()
  await page.keyboard.press("Escape")
  await page.locator("header").getByRole("link", { name: /Review/ }).click()
  review = page.getByRole("form", { name: "Review transaction" })
  await review.getByLabel("Description").fill("Lunch")
  await review.getByRole("button", { name: "Needs" }).click()
  await review.getByRole("combobox").first().selectOption({ label: "Cafe" })
  await review.getByRole("button", { name: "Finalize" }).click()
  await expect(page.getByLabel("Review progress")).toHaveText("1 finalized · 0 skipped")
  await expect(review.getByLabel("Description")).toHaveValue("Coffee")
  await review.getByRole("button", { name: "Confirm selected tag" }).click()
  await review.getByRole("button", { name: "Finalize" }).click()
  await expect(page.getByLabel("Review progress")).toHaveText("2 finalized · 0 skipped")
  await expect(page.getByText("Review complete.")).toBeVisible()
})
