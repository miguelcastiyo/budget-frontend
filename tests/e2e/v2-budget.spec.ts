import { expect, test } from "@playwright/test"
import { setupEncryptedFixture } from "./encrypted-fixture"

test.skip(process.env.NEXT_PUBLIC_BUDGET_V2_ENABLED !== "true", "Requires v2 availability")
test.use({ actionTimeout: 12000 })

test("create, update, inherit and display a budget in both interfaces", async ({ page }) => {
  test.setTimeout(90000)
  await setupEncryptedFixture(page, true)
  await page.getByTestId("v2-overview").getByRole("button", { name: "Set budget" }).click()
  const dialog = page.getByRole("dialog", { name: "Edit Budget" })
  await expect(dialog).toBeVisible()
  await dialog.getByLabel("Monthly take-home income").fill("1000")
  await dialog.getByRole("button", { name: /Save Budget Starting/ }).click()
  await expect(dialog).toHaveCount(0)
  const budget = page.getByTestId("v2-budget")
  await expect(budget.getByLabel("Monthly budget")).toContainText("$1,000.00")
  await expect(budget.getByLabel("Budget allocation")).toContainText("$500.00")
  await expect(budget).toContainText("exact budget")
  await expect(budget).toContainText("1 versions")
  await budget.getByRole("button", { name: "Edit budget" }).click()
  await dialog.getByLabel("Monthly take-home income").fill("1200")
  await dialog.getByRole("button", { name: /Update .* Budget/ }).click()
  await expect(dialog).toHaveCount(0)
  await expect(budget.getByLabel("Monthly budget")).toContainText("$1,200.00")
  await page.getByRole("navigation", { name: "Primary desktop" }).getByRole("link", { name: "Home" }).click()
  await expect(page.getByLabel("Month summary")).toContainText("$1,200.00")
  await expect(page.getByLabel("Categories")).toContainText("$600.00")
  await page.getByRole("button", { name: "Add", exact: true }).click()
  const capture = page.getByRole("form", { name: "Quick Capture" })
  await capture.getByLabel("Amount").fill("99")
  await capture.getByLabel("Description").fill("Pending purchase")
  await capture.getByRole("button", { name: "Save to Review" }).click()
  await expect(page.getByLabel("Month actions")).toContainText("1 to sort")
  await expect(page.getByLabel("Month summary")).toContainText("$0.00 of $1,200.00")
  await page.getByRole("navigation", { name: "Primary desktop" }).getByRole("link", { name: "More" }).click()
  const toggle = page.getByRole("switch", { name: "Use v2 interface" })
  await toggle.click()
  await page.getByRole("link", { name: "Overview", exact: true }).first().click()
  await expect(page.getByText("$1,200.00").first()).toBeVisible()
  await page.getByRole("link", { name: "Settings", exact: true }).first().click()
  await toggle.click()
  await page.getByRole("navigation", { name: "Primary desktop" }).getByRole("link", { name: "Home" }).click()
  await expect(page.getByLabel("Month summary")).toContainText("$1,200.00")
  await page.getByRole("navigation", { name: "Primary desktop" }).getByRole("link", { name: "More" }).click()
  await page.getByRole("link", { name: /Budget/ }).first().click()
  await expect(budget.getByLabel("Monthly budget")).toContainText("$1,200.00")
  await budget.getByRole("button", { name: "Previous month" }).click()
  await expect(budget).toContainText("No budget has been created")
  await expect(budget.getByLabel("Monthly budget")).toContainText("No budget yet")
  await budget.getByRole("button", { name: "Previous month" }).click()
  await budget.getByRole("button", { name: "Set budget" }).click()
  await dialog.getByLabel("Monthly take-home income").fill("900")
  await dialog.getByRole("tab", { name: "By Amount" }).click()
  await dialog.getByLabel("Needs", { exact: true }).fill("1")
  await expect(dialog.getByRole("button", { name: "Fix issues before saving" })).toBeDisabled()
  await dialog.getByLabel("Needs", { exact: true }).fill("450")
  await dialog.getByRole("button", { name: /Save Budget Starting/ }).click()
  await expect(dialog).toHaveCount(0)
  await budget.getByRole("button", { name: "Next month" }).click()
  await expect(budget).toContainText("using the budget from")
  await expect(budget.getByLabel("Monthly budget")).toContainText("$900.00")
  await budget.getByRole("button", { name: "Next month" }).click()
  await expect(budget).toContainText("exact budget")
  await expect(budget.getByRole("button", { name: "Next month" })).toBeDisabled()
})

test("v2 budget editor validates hourly income and fits mobile dark mode", async ({ page }) => {
  test.setTimeout(90000)
  await setupEncryptedFixture(page, true)
  await page.getByTestId("v2-overview").getByRole("button", { name: "Set budget" }).click()
  await page.setViewportSize({ width: 375, height: 667 })
  await page.evaluate(() => document.documentElement.classList.add("dark"))
  const dialog = page.getByRole("dialog", { name: "Edit Budget" })
  await expect(dialog).toHaveCSS("background-color", "rgb(22, 23, 26)")
  await dialog.getByRole("tab", { name: "Hourly", exact: true }).first().click()
  await dialog.getByLabel("Hourly rate").fill("25")
  await dialog.getByLabel("Hours/week").fill("40")
  await dialog.getByLabel("Needs", { exact: true }).fill("10")
  await expect(dialog.getByRole("button", { name: "Fix issues before saving" })).toBeDisabled()
  await dialog.getByLabel("Needs", { exact: true }).fill("50")
  await expect(dialog.getByRole("button", { name: /Save Budget Starting/ })).toBeEnabled()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await dialog.getByRole("button", { name: /Save Budget Starting/ }).click()
  await expect(page.getByTestId("v2-budget").getByLabel("Monthly budget")).toContainText("$4,333.33")
})

test("a failed budget save keeps the draft visible for retry", async ({ page }) => {
  test.setTimeout(90000)
  await setupEncryptedFixture(page, true)
  await page.getByTestId("v2-overview").getByRole("button", { name: "Set budget" }).click()
  const dialog = page.getByRole("dialog", { name: "Edit Budget" })
  await dialog.getByLabel("Monthly take-home income").fill("1000")
  await page.route("**/api/v1/me/encrypted-records", route => route.fulfill({ status: 500, json: { error: { code: "TEST_FAILURE", message: "Save failed" } } }))
  await dialog.getByRole("button", { name: /Save Budget Starting/ }).click()
  const globalError = page.getByRole("dialog", { name: "Something went wrong" })
  await expect(globalError).toBeVisible()
  await globalError.getByRole("button", { name: "Close" }).first().click()
  await expect(dialog.getByRole("alert")).toBeVisible()
  await expect(dialog.getByLabel("Monthly take-home income")).toHaveValue("1000")
  await page.unroute("**/api/v1/me/encrypted-records")
  await dialog.getByRole("button", { name: /Save Budget Starting/ }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByTestId("v2-budget").getByLabel("Monthly budget")).toContainText("$1,000.00")
})
