    await main.getByRole("button", { name: "Add money" }).click()
    const entry = page.getByRole("dialog", { name: "Add money" })
    await entry.getByRole("button", { name: /Link existing savings transaction/ }).click()
    await entry.getByLabel("Search savings transactions").fill("Reserve tag")
    await entry.locator("#fund-transaction-link").click()
    await page.getByRole("option", { name: /Existing savings.*200.*Reserve tag/ }).click()
    await expect(entry.getByLabel("Amount to add")).toHaveValue("200.00")
    await entry.getByLabel("Fund note").fill("Custom linked note")
    const before = fixture.bodies.length
    fixture.failNext(1)
    await entry.getByRole("button", { name: "Save entry" }).click()
    await expect(entry.getByRole("button", { name: "Retry original save" })).toBeVisible()
    if (recovery === "retry") {
      await entry.getByRole("button", { name: "Retry original save" }).click()
      await expect(entry).toHaveCount(0)
      expect(fixture.bodies[before]).toBe(fixture.bodies[before + 1])
    } else {
      await page.reload()
      await page.getByRole("button", { name: "Use Vault passphrase" }).click()
      await page.getByLabel("Vault passphrase", { exact: true }).fill("test v2 vault password 2026")
      await page.getByRole("button", { name: "Unlock Vault" }).click()
      await main.getByRole("button", { name: "Add money" }).click()
      await expect(entry).toContainText("Previous contribution confirmed")
      await entry.getByRole("button", { name: "Close" }).click()
      expect(fixture.bodies.length).toBe(before + 1)
    }
    await expect(main).toContainText("$200.00")
    await page.getByRole("link", { name: "Transactions", exact: true }).first().click()
