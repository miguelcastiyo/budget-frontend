import { expect, test } from "@playwright/test"
import { setupEncryptedFixture } from "./encrypted-fixture"

test.skip(process.env.NEXT_PUBLIC_BUDGET_V2_ENABLED !== "true", "Requires v2 availability")
test.use({ actionTimeout: 12000 })

test("fund creation, ledger mutations, editing and interface parity", async ({ page }) => {
  test.setTimeout(90000)
  await setupEncryptedFixture(page, true)
  await page.getByRole("link", { name: /Funds/ }).first().click()
  const main = page.getByTestId("v2-funds")
  await expect(main).toContainText("No active funds yet")
  await main.getByRole("button", { name: "New fund" }).filter({ visible: true }).first().click()
  const create = page.getByRole("dialog", { name: "Create fund" })
  await create.getByRole("button", { name: "Create fund" }).click()
  await expect(create).toContainText("Fund name is required")
  await create.getByLabel("Name", { exact: true }).fill("Emergency")
  await create.getByLabel("Goal amount").fill("50000")
  await create.locator("#fund-target-month").click()
  await page.locator('[data-slot="popover-content"]').getByRole("button", { name: "Jan", exact: true }).click()
  const targetMonth = await create.locator("#fund-target-month").innerText()
  await create.getByLabel("Starting balance").fill("10000")
  await create.getByLabel("Notes").fill("Safety reserve")
  await create.getByRole("button", { name: "Create fund" }).click()
  await expect(create).toHaveCount(0)
  await expect(main.getByRole("link", { name: "Open Emergency" })).toContainText("$100.00")
  await main.getByRole("link", { name: "Open Emergency" }).click()
  await expect(main).toContainText("Safety reserve")
  await expect(main).toContainText("Starting balance")
  await main.getByRole("button", { name: "Add money" }).click()
  const entry = page.getByRole("dialog", { name: "Add money" })
  await entry.getByLabel("Amount to add").fill("2500")
  await entry.getByLabel("Fund note").fill("Deposit")
  await entry.getByRole("button", { name: "Save entry" }).click()
  await expect(entry).toHaveCount(0)
  await expect(main).toContainText("$125.00")
  await expect(main).toContainText("Deposit")
  await main.getByRole("button", { name: "Use money" }).click()
  const use = page.getByRole("dialog", { name: "Use money" })
  await use.getByLabel("Amount to use").fill("1000")
  await use.getByRole("button", { name: "Save entry" }).click()
  await expect(use).toHaveCount(0)
  await expect(main).toContainText("$115.00")
  const depositRow = main.getByText("Deposit", { exact: true }).locator("../..").locator("..")
  await depositRow.getByRole("button", { name: /Entry actions/ }).click()
  await page.getByRole("menuitem", { name: "Edit entry" }).click()
  const editEntry = page.getByRole("dialog", { name: "Edit fund entry" })
  await editEntry.getByLabel("Amount to add").fill("3000")
  await editEntry.getByRole("button", { name: "Save changes" }).click()
  await expect(editEntry).toHaveCount(0)
  await expect(main).toContainText("$120.00")
  await depositRow.getByRole("button", { name: /Entry actions/ }).click()
  await page.getByRole("menuitem", { name: "Delete entry" }).click()
  await page.getByRole("dialog", { name: "Delete this entry?" }).getByRole("button", { name: "Delete entry" }).click()
  await expect(main).toContainText("$90.00")
  await main.getByRole("button", { name: "Fund actions for Emergency" }).click()
  await page.getByRole("menuitem", { name: "Edit fund" }).click()
  const edit = page.getByRole("dialog", { name: "Edit fund" })
  await expect(edit.getByLabel("Notes")).toHaveValue("Safety reserve")
  await expect(edit.locator("#fund-target-month")).toHaveText(targetMonth)
  await edit.getByLabel("Name", { exact: true }).fill("Rainy day")
  await edit.getByRole("button", { name: "Save changes" }).click()
  await expect(edit).toHaveCount(0)
  await expect(main).toContainText("Rainy day")
  await expect(main).toContainText("Safety reserve")
  await main.getByRole("button", { name: "Fund actions for Rainy day" }).click()
  await page.getByRole("menuitem", { name: "Archive fund" }).click()
  await expect(main).toContainText("Archived")
  await expect(main.getByRole("button", { name: "Add money" })).toBeDisabled()
  await main.getByRole("button", { name: "Fund actions for Rainy day" }).click()
  await page.getByRole("menuitem", { name: "Restore fund" }).click()
  await expect(main.getByRole("button", { name: "Add money" })).toBeEnabled()
  await page.getByRole("link", { name: "Settings", exact: true }).first().click()
  await page.getByRole("switch", { name: "Use v2 interface" }).click()
  await page.getByRole("link", { name: "Insights", exact: true }).first().click()
  await page.getByRole("link", { name: "Open", exact: true }).first().click()
  await expect(page.getByTestId("v2-funds")).toHaveCount(0)
  await expect(page.getByRole("link", { name: "Open Rainy day" })).toContainText("$90.00")
})

test("v2 Fund dialog and target picker fit phone and desktop widths", async ({ page }) => {
  test.setTimeout(90000)
  await setupEncryptedFixture(page, true)
  await page.getByRole("link", { name: /Funds/ }).first().click()
  for (const width of [375, 430, 1280]) {
    await page.setViewportSize({ width, height: width === 1280 ? 800 : 844 })
    await page.evaluate(() => document.documentElement.classList.add("dark"))
    const main = page.getByTestId("v2-funds")
    await main.getByRole("button", { name: "New fund" }).filter({ visible: true }).first().click()
    const dialog = page.getByRole("dialog", { name: "Create fund" })
    await expect(dialog).toHaveCSS("background-color", "rgb(22, 23, 26)")
    await dialog.getByLabel("Name", { exact: true }).fill("Draft")
    await dialog.getByLabel("Goal amount").fill("50000")
    await dialog.locator("#fund-target-month").click()
    const picker = page.locator('[data-slot="popover-content"]').filter({ visible: true })
    await expect(picker).toHaveCSS("background-color", "rgb(22, 23, 26)")
    await page.keyboard.press("Escape")
    await expect(dialog.getByLabel("Name", { exact: true })).toHaveValue("Draft")
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await dialog.getByRole("button", { name: "Close" }).click()
  }
})

test("a failed Fund save leaves its draft available to retry", async ({ page }) => {
  test.setTimeout(90000)
  await setupEncryptedFixture(page, true)
  await page.getByRole("link", { name: /Funds/ }).first().click()
  await page.getByTestId("v2-funds").getByRole("button", { name: "New fund" }).filter({ visible: true }).first().click()
  const dialog = page.getByRole("dialog", { name: "Create fund" })
  await dialog.getByLabel("Name", { exact: true }).fill("Unsent fund")
  await page.route("**/api/v1/me/encrypted-records/batch", route => route.fulfill({ status: 500, json: { error: { code: "TEST_FAILURE", message: "Save failed" } } }))
  await dialog.getByRole("button", { name: "Create fund" }).click()
  const error = page.getByRole("dialog", { name: "Something went wrong" })
  await expect(error).toBeVisible()
  await error.getByRole("button", { name: "Close" }).first().click()
  await expect(dialog.getByLabel("Name", { exact: true })).toHaveValue("Unsent fund")
  await expect(dialog).toContainText("Save failed")
  await page.unroute("**/api/v1/me/encrypted-records/batch")
  await dialog.getByRole("button", { name: "Create fund" }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole("link", { name: "Open Unsent fund" })).toBeVisible()
})
