async function capture(page: Page, amount: string, description: string) {
  await page.getByRole("button", { name: "Add", exact: true }).click()
  const form = page.getByRole("form", { name: "Quick Capture" })
  await form.getByLabel("Amount").fill(amount)
  await form.getByLabel("Description").fill(description)
  await form.getByRole("button", { name: "Save to Review" }).click()
  await expect(form).toHaveCount(0)
}

test("v2 Review requires category and explicit tag confirmation, then supports Undo", async ({ page }) => {
  test.setTimeout(90000)
  await setup(page, true)
  await capture(page, "12.50", "Coffee")
  await page.getByRole("link", { name: /Review/ }).first().click()
  const form = page.getByRole("form", { name: "Review transaction" })
  await expect(form).toContainText("Coffee")
  await expect(form.getByRole("button", { name: "All tags" })).toHaveCount(0)
  await form.getByRole("button", { name: /Needs/ }).click()
  await expect(form.getByRole("button", { name: "Confirm & Next" })).toBeDisabled()
  await form.getByRole("button", { name: "All tags" }).click()
  const picker = page.getByRole("dialog", { name: "All tags" })
  await picker.getByLabel("New tag name").fill("Cafe")
  await picker.getByRole("button", { name: "Create tag" }).click()
  await expect(picker.getByRole("button", { name: "Cafe" })).toBeVisible()
  await picker.getByRole("button", { name: "Done" }).click()
  await expect(form.getByRole("button", { name: "Confirm & Next" })).toBeEnabled()
  await expect(page.getByLabel("Review progress")).toHaveAttribute("aria-valuenow", "0")
  await form.getByRole("button", { name: "Confirm & Next" }).click()
  await expect(page.getByRole("status").filter({ hasText: "Transaction finalized" })).toBeVisible()
  await expect(page.getByLabel("Review progress")).toHaveAttribute("aria-valuenow", "1")
  await page.getByRole("button", { name: "Undo" }).click()
  await expect(page.getByRole("status").filter({ hasText: "Returned to Review" })).toBeVisible()
  await expect(page.getByRole("form", { name: "Review transaction" })).toBeVisible()
})

