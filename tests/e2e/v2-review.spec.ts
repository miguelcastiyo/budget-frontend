test("a recovery capability change preserves an active review draft", async ({ page }) => {
  test.setTimeout(90000)
  await setup(page, true)
  await capture(page, "8.00", "Before")
  await page.getByRole("link", { name: /Review/ }).first().click()
  const form = page.getByRole("form", { name: "Review transaction" })
  await form.getByRole("button", { name: "Edit details" }).click()
  const edit = page.getByRole("dialog", { name: "Edit details" })
  await edit.getByLabel("Description").fill("Unfinished edit")
  await page.route("**/api/pending-capabilities", route => route.fulfill({ json: { capture: false, recovery: false } }))
  await page.evaluate(() => document.dispatchEvent(new Event("visibilitychange")))
  await expect(edit.getByLabel("Description")).toBeDisabled()
  await edit.getByRole("button", { name: "Close" }).click()
  await expect(form).toContainText("Unfinished edit")
  await expect(form.getByRole("button", { name: /Needs/ })).toBeDisabled()
  await page.route("**/api/pending-capabilities", route => route.fulfill({ json: { capture: true, recovery: true } }))
  await page.evaluate(() => document.dispatchEvent(new Event("visibilitychange")))
  await expect(form.getByRole("button", { name: /Needs/ })).toBeEnabled()
  await expect(form).toContainText("Unfinished edit")
})
