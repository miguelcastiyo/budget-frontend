test("v2 Activity shows finalized records separately from pending capture", async ({ page }) => {
  test.setTimeout(90000)
  await setup(page, true)
  await capture(page, "12.50", "Ledger coffee")
  await page.getByRole("link", { name: /Transactions|Activity/ }).first().click()
  const ledger = page.getByRole("region", { name: "Activity transactions" })
  await expect(ledger).toBeVisible()
  await expect(ledger).not.toContainText("Ledger coffee")
  await page.getByRole("link", { name: /Review/ }).first().click()
  const form = page.getByRole("form", { name: "Review transaction" })
  await form.getByRole("button", { name: /Needs/ }).click()
  await form.getByRole("button", { name: "All tags" }).click()
  const picker = page.getByRole("dialog", { name: "All tags" })
  await picker.getByLabel("New tag name").fill("Cafe")
  await picker.getByRole("button", { name: "Create tag" }).click()
  await picker.getByRole("button", { name: "Done" }).click()
  await form.getByRole("button", { name: "Confirm & Next" }).click()
  await expect(page.getByRole("status").filter({ hasText: "Transaction finalized" })).toBeVisible()
  await page.getByRole("link", { name: /Transactions|Activity/ }).first().click()
  await expect(ledger.getByRole("button", { name: /Ledger coffee/ })).toContainText("Cafe")
  await expect(ledger.getByRole("button", { name: /Ledger coffee/ })).toContainText("12.50")
  await page.getByPlaceholder("Search transactions...").filter({ visible: true }).fill("no match")
  await expect(ledger).toContainText("No matching transactions")
  await page.getByRole("button", { name: "Clear filters", exact: true }).click()
  await expect(ledger.getByRole("button", { name: /Ledger coffee/ })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.evaluate(() => document.documentElement.classList.add("dark"))
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await ledger.getByRole("button", { name: /Ledger coffee/ }).click()
  await expect(page.getByRole("dialog").getByText("Ledger coffee")).toBeVisible()
})
