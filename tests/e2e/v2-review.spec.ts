test("swipe, missing details and opening Add preserve the current review", async ({ page }) => {
  test.setTimeout(90000)
  await setup(page, true)
  await capture(page, "6.00", "")
  await page.getByRole("link", { name: /Review/ }).first().click()
  const form = page.getByRole("form", { name: "Review transaction" })
  const card = form.getByTestId("review-swipe-card")
  const box = await card.boundingBox()
  if (!box) throw new Error("Swipe card missing")
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 + 115, box.y + box.height / 2, { steps: 5 })
  await page.mouse.up()
  await expect(form.getByRole("button", { name: "Confirm & Next" })).toBeVisible()
  await form.getByRole("button", { name: "Edit details" }).click()
  const edit = page.getByRole("dialog", { name: "Edit details" })
  await edit.getByLabel("Description").fill("Bus ticket")
  await edit.getByRole("button", { name: "Done" }).click()
  await expect(form).toContainText("Bus ticket")
  await page.getByRole("button", { name: "Add", exact: true }).click()
  const quick = page.getByRole("form", { name: "Quick Capture" })
  await quick.getByLabel("Description").fill("Another")
  await quick.getByRole("button", { name: "Save to Review" }).click()
  await expect(quick).toHaveCount(0)
  await expect(form).toContainText("Bus ticket")
})

