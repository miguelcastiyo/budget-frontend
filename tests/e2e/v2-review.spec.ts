  const card = form.getByTestId("review-swipe-card")
  const box = await card.boundingBox()
  if (!box) throw new Error("Swipe card missing")
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 + 115, box.y + box.height / 2, { steps: 5 })
