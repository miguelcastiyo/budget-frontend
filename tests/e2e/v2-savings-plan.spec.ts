import { expect, test } from "@playwright/test"
import { setupEncryptedFixture } from "./encrypted-fixture"

test.skip(process.env.NEXT_PUBLIC_BUDGET_V2_ENABLED !== "true", "Requires v2 availability")
test.use({ actionTimeout: 12000 })

test("monthly allocations use the same encrypted data in v2 and Classic", async ({ page }) => {
  test.setTimeout(120000)
  const fixture = await setupEncryptedFixture(page, true)
  await page.getByTestId("v2-overview").getByRole("button", { name: "Set budget" }).click()
  const budgetDialog = page.getByRole("dialog", { name: "Edit Budget" })
  await budgetDialog.getByLabel("Monthly take-home income").fill("1000")
  await budgetDialog.getByRole("button", { name: /Save Budget Starting/ }).click()
  await expect(budgetDialog).toHaveCount(0)
  await page.getByRole("link", { name: "Insights", exact: true }).first().click()
  await page.getByRole("link", { name: "Open", exact: true }).first().click()
  const funds = page.getByTestId("v2-funds")
  await funds.getByRole("button", { name: "New fund" }).filter({ visible: true }).first().click()
  const dialog = page.getByRole("dialog", { name: "Create fund" })
  await dialog.getByLabel("Name", { exact: true }).fill("Emergency")
  await dialog.getByRole("button", { name: "Create fund" }).click()
  await expect(dialog).toHaveCount(0)
  await funds.getByRole("link", { name: /Plan |View plan/ }).click()
  const plan = page.getByTestId("v2-savings-plan")
  await expect(plan.getByRole("heading", { name: "Savings Plan" })).toBeVisible()
  await expect(plan).toContainText("$200")
  await plan.getByRole("button", { name: "Plan savings" }).click()
  await plan.getByRole("button", { name: "Add a fund" }).click()
  await plan.getByRole("button", { name: "Emergency" }).click()
  const input = plan.getByLabel("Planned amount for Emergency")
  await input.fill("75")
  await expect(plan.getByRole("button", { name: "Previous month" })).toBeDisabled()
  fixture.failBeforeNext(1)
  await plan.getByRole("button", { name: "Save plan" }).click()
  const globalError = page.getByRole("dialog", { name: "Something went wrong" })
  if (await globalError.isVisible()) await globalError.getByRole("button", { name: "Close" }).first().click()
  await expect(plan.getByRole("alert")).toBeVisible()
  await expect(input).toHaveValue("75")
  await plan.getByRole("button", { name: "Save plan" }).click()
  await expect(plan).toContainText("$75 planned")
  await expect(plan).toContainText("$125")
  await plan.getByRole("button", { name: "Edit plan" }).click()
  await input.fill("250")
  await expect(plan.getByRole("button", { name: "Save plan" })).toBeDisabled()
  await input.fill("90")
  await plan.getByRole("button", { name: "Save plan" }).click()
  await expect(plan).toContainText("$90 planned")
  await page.getByRole("button", { name: "Add", exact: true }).click()
  const capture = page.getByRole("form", { name: "Quick Capture" })
  await capture.getByLabel("Amount").fill("10.00")
  await capture.getByLabel("Description").fill("Savings contribution")
  await capture.getByRole("button", { name: "Save to Review" }).click()
  await expect(plan).toContainText("$0 of $200")
  await page.getByRole("link", { name: /Review/ }).first().click()
  const review = page.getByRole("form", { name: "Review transaction" })
  await review.getByRole("button", { name: /Savings/ }).click()
  await review.getByRole("button", { name: "All tags" }).click()
  const picker = page.getByRole("dialog", { name: "All tags" })
  await picker.getByLabel("New tag name").fill("Savings")
  await picker.getByRole("button", { name: "Create tag" }).click()
  await picker.getByRole("button", { name: "Done" }).click()
  await review.getByRole("button", { name: "Confirm & Next" }).click()
  await expect(page.getByRole("status").filter({ hasText: "Transaction finalized" })).toBeVisible()
  await page.getByRole("link", { name: "Insights", exact: true }).first().click()
  await page.getByRole("link", { name: "Open", exact: true }).first().click()
  await funds.getByRole("link", { name: "Open Emergency" }).click()
  await funds.getByRole("button", { name: "Add money" }).click()
  const entry = page.getByRole("dialog", { name: "Add money" })
  await entry.getByRole("button", { name: /Link existing savings transaction/ }).click()
  await entry.locator("#fund-transaction-link").click()
  await page.getByRole("option", { name: /Savings contribution/ }).click()
  await entry.getByRole("button", { name: "Save entry" }).click()
  await expect(entry).toHaveCount(0)
  await funds.getByRole("link", { name: "View Savings Plan" }).click()
  await expect(plan).toContainText("$10 directed")
  await expect(plan).toContainText("$10 of $200")
  await plan.getByRole("button", { name: "Previous month" }).click()
  await expect(plan).toContainText("doesn’t have a budget yet")
  await plan.getByRole("button", { name: "Next month" }).click()
  await expect(plan).toContainText("$90 planned")
  await page.getByRole("link", { name: "Settings", exact: true }).first().click()
  await page.getByRole("switch", { name: "Use v2 interface" }).click()
  await page.getByRole("link", { name: "Insights", exact: true }).first().click()
  await page.getByRole("link", { name: "Open", exact: true }).first().click()
  await page.getByRole("link", { name: "View plan" }).click()
  await expect(page.getByTestId("v2-savings-plan")).toHaveCount(0)
  await expect(page.getByText("$90 planned").first()).toBeVisible()
  await expect(page.getByText("$110 of Savings budget unassigned")).toBeVisible()
})

test("v2 Savings Plan fits mobile and desktop in both themes", async ({ page }) => {
  test.setTimeout(90000)
  await setupEncryptedFixture(page, true)
  await page.goto("/funds/savings-plan")
  await page.getByRole("button", { name: "Use Vault passphrase" }).click()
  await page.getByLabel("Vault passphrase", { exact: true }).fill("test v2 vault password 2026")
  await page.getByRole("button", { name: "Unlock Vault" }).click()
  const plan = page.getByTestId("v2-savings-plan")
  await expect(plan).toContainText("doesn’t have a budget yet")
  for (const width of [375, 430, 1280]) {
    await page.setViewportSize({ width, height: 844 })
    for (const dark of [false, true]) {
      await page.evaluate((value) => document.documentElement.classList.toggle("dark", value), dark)
      await expect(plan).toHaveCSS("background-color", dark ? "rgb(22, 23, 26)" : "rgb(251, 251, 250)")
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    }
  }
})
